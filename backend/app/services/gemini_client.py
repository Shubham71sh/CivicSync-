def call_gemini(prompt: str) -> str:
    """
    Calls Gemini API (or Groq API fallback) with the given prompt.
    Returns the response text string.
    """
    # 1. Primary: Try Gemini Client from app.config.gemini
    try:
        from app.config.gemini import get_gemini_client
        client = get_gemini_client()
        if client is not None:
            response = client.models.generate_content(
                model="gemini-flash-lite-latest",
                contents=prompt
            )
            if response and hasattr(response, "text") and response.text:
                return response.text.strip()
    except Exception as gemini_err:
        logger.warning(f"Gemini API request failed ({gemini_err}). Trying Groq fallback...")

    # 2. Secondary: Try Groq API if key is present
    if GROQ_API_KEY:
        try:
            headers = {
                "Content-Type": "application/json",
                "Authorization": f"Bearer {GROQ_API_KEY}",
            }
            payload = {
                "model": GROQ_MODEL,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": 0.7,
                "max_tokens": 2048,
            }
            with httpx.Client(timeout=60) as client:
                resp = client.post(GROQ_URL, json=payload, headers=headers)
            if resp.status_code == 200:
                data = resp.json()
                return data["choices"][0]["message"]["content"].strip()
            else:
                logger.warning(f"Groq API error {resp.status_code}: {resp.text}")
        except Exception as groq_err:
            logger.warning(f"Groq API call error: {groq_err}")

    # 3. Fallback for development/offline without API keys
    logger.warning("No active LLM API keys. Using built-in translation engine.")
    return _generate_mock_translation(prompt)

